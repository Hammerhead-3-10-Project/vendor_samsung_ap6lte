#!/usr/bin/env python3
"""Generate sepolicy/file_contexts and sepolicy/vendor_types.te of the vendor tree.

    python3 gen_sepolicy.py <stock vendor dump> <lineage out/target/product/a6plte/obj/ETC> <repo dir>

The build labels the files of vendor.img with file_contexts.bin and checks the labels against its own policy, so the
vendor path rules of the stock vendor_file_contexts must be known to the build and every type they use must exist
in it. This script keeps from the stock vendor_file_contexts only the rules for /vendor and /odm paths that the build
does not already have, and declares the types that are missing as empty stubs.
The stubs exist only for the build. On the phone the stock Samsung policy runs (proprietary/selinux/): the build's own
vendor_sepolicy.cil, vendor_file_contexts, ... are replaced by it (Android.mk, LOCAL_OVERRIDES_PACKAGES).

WARNING: do not point the second argument at the out/ of a build that already used sepolicy/ (the rules would be
counted as "already in the build" and the output would be empty). Pass any non-directory (e.g. "none") to use the
snapshots known_*.txt, which were taken from a build without these rules. To refresh them, build with
BOARD_SEPOLICY_DIRS lacking this directory, then run with that out/.

The ETC directory is used (with seinfo) to know which types and rules the build already has; the answer is kept in
sepolicy/known_types.txt and sepolicy/known_contexts.txt so the generator can run without a build tree.
"""
import os, re, subprocess, sys

src, etc, dst = [os.path.abspath(a) for a in sys.argv[1:4]]
sp = os.path.join(dst, 'sepolicy'); os.makedirs(sp, exist_ok=True)
KT, KC = os.path.join(sp, 'known_types.txt'), os.path.join(sp, 'known_contexts.txt')

def parse(lines):
    out = {}
    for l in lines:
        s = l.strip()
        if not s or s.startswith('#'):
            continue
        p = s.split()
        out[(p[0], p[1] if len(p) == 3 else '')] = p[-1]
    return out

if os.path.isdir(etc):
    out = subprocess.run(['seinfo', os.path.join(etc, 'sepolicy_intermediates/sepolicy'), '--type'],
                         capture_output=True, text=True, check=True).stdout.splitlines()[1:]
    open(KT, 'w').write('\n'.join(sorted(t.strip() for t in out if t.strip())) + '\n')
    known = []
    for f in ('plat_file_contexts_intermediates/plat_file_contexts',
              'vendor_file_contexts_intermediates/vendor_file_contexts'):
        known += [l for l in open(os.path.join(etc, f)) if l.strip() and not l.startswith('#')]
    open(KC, 'w').write(''.join(known))
known_types = set(open(KT).read().split())
known_ctx = parse(open(KC))

stock = [l.rstrip('\n') for l in open(os.path.join(src, 'etc/selinux/vendor_file_contexts'))]
def vendor_rule(l):
    s = l.strip()
    return bool(s) and not s.startswith('#') and s.split()[0].startswith(
        ('/vendor', '/(vendor', '/system/vendor', '/(system/vendor', '/odm', '/(odm'))
# Rules of the stock file that must not be used. The stock vendor_file_contexts has two rules that match
# android.hardware.drm@1.2-service.widevine: this one (escaped dot, hal_drm_default_exec) and a later one with an
# unescaped dot (hal_drm_widevine_exec). The stock image carries hal_drm_widevine_exec, but the build orders rules by
# specificity and the longer escaped regex wins, so the file would get hal_drm_default_exec.
DROP = {r'/(vendor|system/vendor)/bin/hw/android\.hardware\.drm@1\.2-service\.widevine'}
keep, dup, conflict = [], 0, []
for l in stock:
    if not vendor_rule(l):
        continue
    key = (l.split()[0], l.split()[1] if len(l.split()) == 3 else '')
    ctx = l.split()[-1]
    if key[0] in DROP:
        continue
    if key in known_ctx:
        if known_ctx[key] == ctx: dup += 1
        else: conflict.append((key, ctx, known_ctx[key]))
        continue
    keep.append(l.strip())
types = sorted({re.search(r'u:object_r:([^:]+):s0', l).group(1) for l in keep} - known_types)

with open(os.path.join(sp, 'file_contexts'), 'w') as f:
    f.write('# Rules for /vendor and /odm of the stock Samsung vendor_file_contexts that the build does not have.\n'
            '# Generated by gen_sepolicy.py. Used to label vendor.img.\n')
    f.write('\n'.join(keep) + '\n')
with open(os.path.join(sp, 'vendor_types.te'), 'w') as f:
    f.write('# Types of sepolicy/file_contexts that the build policy does not define. Build-time stubs only: the policy\n'
            '# that runs on the phone is the stock Samsung one (proprietary/selinux/). Generated by gen_sepolicy.py.\n')
    for t in types:
        f.write('type %s, %sfile_type, vendor_file_type;\n' % (t, 'exec_type, ' if t.endswith('_exec') else ''))
print('rules kept', len(keep), '| already in the build', dup, '| conflicting', len(conflict), '| type stubs', len(types))
for c in conflict[:10]: print('CONFLICT', c)
